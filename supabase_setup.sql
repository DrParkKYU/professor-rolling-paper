-- 1. 롤링페이퍼 메모 테이블 생성
CREATE TABLE public.memos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    author TEXT NOT NULL,
    relationship TEXT,
    content TEXT NOT NULL,
    color TEXT DEFAULT 'yellow',
    emoji TEXT DEFAULT '🎓'
);

-- 2. 보안 정책(Row Level Security, RLS) 활성화
ALTER TABLE public.memos ENABLE ROW LEVEL SECURITY;

-- 3. 누구나 메모를 조회(읽기)할 수 있도록 허용하는 정책
CREATE POLICY "누구나_메모_읽기_가능" 
ON public.memos 
FOR SELECT 
TO public 
USING (true);

-- 4. 누구나 메모를 등록(쓰기)할 수 있도록 허용하는 정책
CREATE POLICY "누구나_메모_작성_가능" 
ON public.memos 
FOR INSERT 
TO public 
WITH CHECK (true);

